#!/bin/sh
# Concatenate the unchanged HORCRUX RTL (packages first) and HorcruxRoCCAdapter.sv into one file that the
# Chisel BlackBox ships to Verilator (same approach as Chipyard's caliptra-aes-acc).
# usage: gen_rtl.sh [out.sv]
set -e
. "$(dirname "$0")/env.sh"
H=$HORCRUX/hw
OUT_SV=${1:-$ROOT/generator/src/main/resources/vsrc/horcrux_rocc.sv}
CP=$H/ip/coprocessors
CVX=$H/vendor/x-heep/hw/vendor/openhwgroup_cv32e40x/rtl
{
  echo "// Generated by horcrux-boom/scripts/gen_rtl.sh from HORCRUX $(git -C $HORCRUX rev-parse --short HEAD 2>/dev/null || echo '?') - do not edit"
  for f in $CVX/include/cv32e40x_pkg.sv $CVX/if_xif.sv $CP/include/cv32e40px_core_v_xif_pkg.sv \
           $CP/include/cv32e40px_pkg.sv $CP/include/horcrux_pkg.sv $CP/keccak/pkg_keccak.sv \
           $(ls $CP/keccak/keccak_*.sv) $(ls $CP/*.sv | grep -v coproc_wrapper) \
           $ROOT/generator/src/main/resources/vsrc/HorcruxRoCCAdapter.sv; do
    echo "// ---- $(basename $f)"; cat $f; echo
  done
} > $OUT_SV
echo "wrote $OUT_SV"
